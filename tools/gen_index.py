    print('统计:', dict(stat))
    print('索引层入库:', len(rows), '条 ->', out)
    print('地区:', dict(Counter(r['region'] for r in rows).most_common(12)))
    print('分类:', dict(Counter(r['category'] for r in rows).most_common()))
    print('层级:', dict(Counter(r['level'] for r in rows)))
    print('年份:', dict(sorted(Counter(r['publish_date'][:4] for r in rows).items())))


