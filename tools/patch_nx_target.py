# -*- coding: utf-8 -*-
"""宁夏装机目标口径判定：以 20GW（《美丽宁夏建设「十五五」规划》）为准。

用户 2026-11-13 决定：宁夏取 20GW，不取汇总表的 10GW。

核对到的原文（宁政发〔2026〕25号 第 18 条）："新建2000万千瓦新型储能项目"，
是「十五五」期间**新建量**口径，不是 2030 年累计装机。
宁夏广电（2026-11）另给出 2030 年口径："宁夏新型储能将达到2000万千瓦/4小时，
年综合利用1200小时以上"——据此可补 duration_h=4，并按 20GW×4h 折算 80GWh。

交叉校验（写进 note，用于反证 10GW 偏低）：
24 省加总 280GW（含宁夏 10）→ 宁夏修正为 20 → 约 290GW；再加青海 10GW → 约 300GW，
与国家《新型能源体系建设「十五五」规划》2030 年 300GW 目标吻合。
"""
import io
import json

P = "data/policies.json"
TARGET = "NX-20260827-01"
CN = "CN-20260506-01"

KEY_POINTS = [
    "「十五五」期间新建 2000 万千瓦（20GW）新型储能项目——是**新建量**口径，不等于 2030 年累计装机",
    "官方 2030 年口径：全区新型储能达 2000 万千瓦/4 小时（折算约 80GWh），年综合利用 1200 小时以上",
    "新能源装机规模力争突破 1 亿千瓦（100GW），同步推进老旧风电场改造、分布式光伏、绿电园区与零碳园区",
    "按 20GW 分摊五年约年均 4GW；2026 年已在清单内的各市电网侧储能合计约 8.3GW（中卫 3.38、宁东 1.0、石嘴山 1.4、银川 1.5+1.0），投放节奏需持续观察",
    "规划未给出电网侧/用户侧结构，也未分解分年度规模，年度节奏以容量电价与清单文件为准",
]

NOTE = (
    "【口径判定】以 20GW 为准（2026-11-13 用户确认）。依据：宁政发〔2026〕25号第18条原文"
    "「新建2000万千瓦新型储能项目」；宁夏广电报道2030年达「2000万千瓦/4小时、年综合利用1200小时以上」。"
    "汇总表的 10GW 对应「实施宁夏千万千瓦新型储能项目」表述，属较低且不同口径，不采用。"
    "【交叉校验】24省加总280GW（含宁夏10）→宁夏修正为20后约290GW，加青海10GW约300GW，"
    "与国家《新型能源体系建设「十五五」规划》2030年300GW吻合，反证10GW偏低。"
    "【注意】20GW是「十五五」新建量，若按累计口径看2030年总量，需叠加2025年底前已建成规模。"
    "原始发文页（nx.gov.cn）截至2026-11-13未检索到直链，暂用北极星转载页；文件落款2026-08-27，北极星2026-09-16发布。"
)


def main():
    d = json.load(io.open(P, encoding="utf-8"))
    items = d["policies"]

    p = [x for x in items if x["id"] == TARGET][0]
    p["star"] = 3
    p["sub_tags"] = ["十五五规划", "新建20GW", "2030年2000万千瓦", "4小时", "年利用1200小时", "新能源100GW"]
    p["summary"] = ("宁夏「十五五」新建2000万千瓦（20GW）新型储能，2030年达2000万千瓦/4小时、"
                    "年综合利用1200小时以上；新能源装机力争突破1亿千瓦")
    p["key_points"] = KEY_POINTS
    p["metrics"]["scale_gw"] = 20.0
    p["metrics"]["scale_gwh"] = 80.0
    p["metrics"]["duration_h"] = 4
    p["metrics"]["note"] = ("「十五五」新建20GW（新建量口径，非累计）；官方2030年「2000万千瓦/4小时」"
                            "折算约80GWh（scale_gwh 为折算值）；年综合利用1200小时以上；新能源装机>100GW；"
                            "汇总表记10GW为误记，不采用")
    p["logic"] = ("20GW/五年≈年均4GW，是全国省级目标中节奏最激进的一档，而宁夏2026年清单投放已约8.3GW，"
                  "前两年节奏大概率超年均；真正的约束不在目标而在外送通道与本地消纳（银东、灵绍、中衡三条直流"
                  "合计2000万千瓦外送容量）以及容量电价165元/kW·年下的项目收益能否覆盖")
    p["note"] = NOTE
    p["last_checked"] = "2026-11-13"

    # 全国汇总条目同步：宁夏由10修正为20
    cn = [x for x in items if x["id"] == CN][0]
    cn["note"] = (cn["note"].rstrip("。") +
                  "。注：宁夏按2026-11-13判定取20GW（原表10GW为误记），24省修正后约290GW；"
                  "若再计入青海2030年10GW，25省合计约300GW，与国家2030年300GW目标吻合。")
    cn["last_checked"] = "2026-11-13"

    json.dump(d, io.open(P, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    print("更新", TARGET, "| star", p["star"], "| scale_gw", p["metrics"]["scale_gw"],
          "| scale_gwh", p["metrics"]["scale_gwh"], "| duration_h", p["metrics"]["duration_h"])
    print("要点 %d 条" % len(p["key_points"]))
    print("CN note 追加完成")


if __name__ == "__main__":
    main()
