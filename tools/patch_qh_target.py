def main():
    d = json.load(io.open(P, encoding="utf-8"))
    items = d["policies"]

    assert not any(p["id"] == NEW_ID for p in items), "ID 已存在"

    # 1) 新增青海条目
    items.append(ITEM)

    # 2) 修正全国汇总条目里「7 省无目标」与辽宁表述
    cn = [p for p in items if p["id"] == "CN-20260506-01"][0]
    kps = cn["key_points"]
    for i, s in enumerate(kps):
        if s.startswith("7 省未设量化目标"):
            kps[i] = ("6 省未设量化目标：广西、福建、海南、新疆、西藏、陕西；青海已于2026-08补设"
                      "2030年10GW目标（见 QH-20260831-01），故不再计入缺口省")
        if "辽宁 3.2 为第一批" in s:
            kps[i] = s.replace("辽宁 3.2 为第一批", "辽宁 5 为2027年目标（3.2 是第一批遴选规模）")
    cn["note"] = (cn["note"].rstrip("。") +
                  "。注：青海2026-08另设2030年10GW目标，25省合计约290GW，280GW口径未含青海。")
    cn["last_checked"] = "2026-11-13"

    json.dump(d, io.open(P, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    print("新增", NEW_ID, "|", ITEM["region"], ITEM["category"], "| scale_gw", ITEM["metrics"]["scale_gw"])
    print("要点", len(ITEM["key_points"]), "条 | 官方链接", OFFICIAL)
    print("CN-20260506-01 要点4 →", kps[3])
    print("CN-20260506-01 要点3 →", kps[2])
    qh = [p for p in items if p["region"] == "青海" and p["category"] == "储能装机目标"]
    print("青海「储能装机目标」条目：", [(p["id"], p["tier"], p["metrics"].get("scale_gw")) for p in qh])


if __name__ == "__main__":
    main()
