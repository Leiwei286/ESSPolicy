def is_city(t):
    if re.search(r'市(?!场)', t):
        return True
    if re.search(r'[州县城](?!场)', t):
        return True
    return any(c in t for c in CITY)


def region_of(t):
    for n, ks in PROV:
        if any(k in t for k in ks):
            return n
    return None


def qty_score(t):
    s = 0
    for pat, w in QTY:
        if re.search(pat, t):
            s += w
    return s


rows = []
for url, v in acc.items():
    d, t = v['date'], v['title']
    if url in known:
        continue
    if d < '2025-01-01':
        continue
    if any(k in t for k in DROP):
        continue
    if is_city(t):
        continue
    prov = region_of(t)
    if prov in KEY or any(any(k in t for k in ks) for ks in KEY_HIT.values()):
        continue
    cats = [c for c, ks in CORE.items() if any(k in t for k in ks)]
    if not cats:
        continue
    key = re.sub(r'[^\u4e00-\u9fa5A-Za-z0-9]', '', t)[:24]
    if key in known_norm:
        continue
    rows.append({
        'date': d, 'region': prov or '全国', 'cats': cats,
        'qty': qty_score(t), 'title': t, 'url': url,
    })

rows.sort(key=lambda x: (-x['qty'], x['date']), reverse=False)
